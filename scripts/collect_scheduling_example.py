"""Compare FIFO with a certified makespan optimum on the same illustrative inputs."""
import argparse
from dataclasses import asdict
import json
from pathlib import Path
import sys


def collect(project, report):
    sys.path.insert(0, str(project / 'src'))
    from strategic_planner.scheduling import (
        ListScheduler, CpSatScheduler, MachinePool, Operation, ProductionJob, SchedulingProblem, run_scheduler,
    )
    from strategic_planner.scheduling.deadlines import FamilyDeadline

    # Chosen illustrative inputs, not observations or outputs of the generative models.
    routes = {
        'A1': [('TRENOLUNA', 2), ('BANCHI', 3), ('ANTIMIX', 1), ('PRONTO', 0)],
        'A2': [('TRENOLUNA', 1), ('RADDR', 2), ('ANTIMIX', 1), ('PRONTO', 0)],
        'B1': [('TRENOLUNA', 2), ('ANTIMIX', 1), ('PRONTO', 0)],
    }
    phases = ['TRENOLUNA', 'BANCHI', 'RADDR', 'ANTIMIX']
    problem = SchedulingProblem(
        jobs=tuple(ProductionJob(name, tuple(Operation(i, phase, duration)
            for i, (phase, duration) in enumerate(route))) for name, route in routes.items()),
        resources=tuple(MachinePool(phase) for phase in phases + ['PRONTO']),
        deadlines=(FamilyDeadline('A', ('A1', 'A2'), 6, 2), FamilyDeadline('B', ('B1',), 8)),
    )
    results = {
        'fifo': run_scheduler(problem, ListScheduler('fifo')),
        'cp_sat': run_scheduler(problem, CpSatScheduler(time_limit_seconds=10, workers=1)),
    }
    assert results['cp_sat'].status.value == 'optimal', 'Do not label an uncertified plan optimal.'
    evidence = {
        'kind': 'illustrative_synthetic_inputs', 'objective': 'makespan',
        'problem': asdict(problem),
        'results': {name: asdict(result) for name, result in results.items()},
    }
    (report/'tables/data/scheduling-example.json').write_text(json.dumps(evidence, indent=2)+'\n')

    colors = {'A1': 'ReportBlue', 'A2': 'teal', 'B1': 'ReportExample!75!black'}
    lines = [r'% Generated by scripts/collect_scheduling_example.py from validated plans.',
        r'\begin{tikzpicture}[x=1.05cm,y=0.7cm,font=\small]']
    for name, title, offset in [('fifo', 'FIFO', 0), ('cp_sat', 'CP-SAT: piano ottimo', -5.7)]:
        result = results[name]
        lines.append(r'\begin{scope}[shift={(0,%g)}]' % offset)
        lines.append(r'\node[anchor=west,font=\small\bfseries] at (-1.9,4) {%s (%g ore)};' % (title, result.schedule.makespan_hours))
        lines.extend([r'\foreach \t in {0,...,8} {',
            r'  \draw[ReportBlue!15,line width=0.4pt] (\t,-0.45) -- (\t,3.45);',
            r'  \node[anchor=north,text=ReportMuted] at (\t,-0.55) {\t};', r'}'])
        for index, phase in enumerate(phases):
            y = 3-index
            lines.append(r'\node[anchor=east] at (-0.18,%s) {\texttt{%s}};' % (y, phase))
            for op in result.schedule.operations:
                if op.macro_phase != phase or op.end_hours == op.start_hours:
                    continue
                color = colors[op.job_id]
                lines.append(r'\path[draw=%s,fill=%s!14,rounded corners=1.2pt,line width=0.7pt] (%g,%g) rectangle (%g,%g);' % (color,color,op.start_hours,y-.3,op.end_hours,y+.3))
                lines.append(r'\node at (%g,%g) {%s};' % ((op.start_hours+op.end_hours)/2,y,op.job_id))
        lines.append(r'\end{scope}')
    lines.extend([r'\node[anchor=north] at (4,-6.85) {Tempo dall\textquotesingle origine [ore]};',r'\end{tikzpicture}'])
    (report/'figures/scheduling-example.tex').write_text('\n'.join(lines)+'\n')
    print(json.dumps({name: {'status': r.status.value, 'makespan_hours': r.schedule.makespan_hours,
        'deadlines': r.deadline_summary} for name, r in results.items()}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', type=Path, required=True)
    parser.add_argument('--report', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    collect(args.project, args.report)
